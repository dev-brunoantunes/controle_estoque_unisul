package constante;

/**
 * Enum que representa as unidades de medida de um produto.
 *
 * @author Kauã
 */
public enum Unidade {
    /**
     * Unidade de medida por unidade.
     */
    UN,
    /**
     * Unidade de medida em quilogramas.
     */
    KG,
    /**
     * Unidade de medida em gramas.
     */
    G,
    /**
     * Unidade de medida em litros.
     */
    L,
    /**
     * Unidade de medida em mililitros.
     */
    ML
}

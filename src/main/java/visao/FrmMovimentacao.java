    private void carregarProdutos() {
        jComboBox2.removeAllItems();
        java.util.List<modelo.Produto> produtos = produtoDAO.listar();
        if (produtos.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Nenhum produto cadastrado.", "Aviso",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        for (modelo.Produto p : produtos) {
            jComboBox2.addItem(p.getNome() + " (ID:" + p.getId() + ")");
        }
    }

    private void carregarTabela() {
        javax.swing.table.DefaultTableModel model
                = (javax.swing.table.DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        java.util.List<modelo.Movimentacao> lista = movimentacaoDAO.listar();
        for (modelo.Movimentacao m : lista) {
            model.addRow(new Object[]{
                m.getId(),
                m.getProduto().getNome(),
                m.getData(),
                m.getQuantidade(),
                m.getTipo().name()
            });
        }
    }

    private modelo.Produto getProdutoSelecionado() {
        int idx = jComboBox2.getSelectedIndex();
        if (idx < 0) {
            return null;
        }
        java.util.List<modelo.Produto> produtos = produtoDAO.listar();
        return produtos.get(idx);
    }

    private void registrarMovimentacao() {
        modelo.Produto produto = getProdutoSelecionado();
        if (produto == null) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Selecione um produto.", "Atenção",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        String tipo = (String) jComboBox1.getSelectedItem();
        int quantidade = (int) jSpinner1.getValue();

        if (quantidade <= 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "A quantidade deve ser maior que zero.", "Atenção",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        modelo.Produto prodAtual = produtoDAO.buscarPorId(produto.getId());

        if (idMovimentacaoSelecionada >= 0) {
            // MODO EDIÇÃO — atualiza o registro existente
            modelo.Movimentacao mov = new modelo.Movimentacao();
            mov.setId(idMovimentacaoSelecionada);
            mov.setProduto(prodAtual);
            mov.setData(java.time.LocalDate.now());
            mov.setQuantidade(quantidade);
            mov.setTipo(enums.TipoMovimentacao.valueOf(tipo));
            movimentacaoDAO.atualizar(mov);

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Movimentação atualizada com sucesso!",
                    "Sucesso", javax.swing.JOptionPane.INFORMATION_MESSAGE);

            // Volta ao modo inserção
            idMovimentacaoSelecionada = -1;
            jButton1.setText("Ok");
            jButton1.setBackground(new java.awt.Color(0, 153, 204));
            jTable1.clearSelection();

        } else {
            // MODO INSERÇÃO — lógica original
            if ("ENTRADA".equals(tipo)) {
                int novaQtd = prodAtual.getQuantidade() + quantidade;
                if (novaQtd > prodAtual.getQuantidadeMaxima()) {
                    javax.swing.JOptionPane.showMessageDialog(this,
                            "⚠ Estoque máximo excedido!\n\n"
                            + "Produto: " + prodAtual.getNome() + "\n"
                            + "Estoque atual: " + prodAtual.getQuantidade() + "\n"
                            + "Quantidade a adicionar: " + quantidade + "\n"
                            + "Total resultante: " + novaQtd + "\n"
                            + "Máximo permitido: " + prodAtual.getQuantidadeMaxima() + "\n\n"
                            + "Operação cancelada.",
                            "Limite Máximo", javax.swing.JOptionPane.WARNING_MESSAGE);
                    return;
                }
                prodAtual.entradaEstoque(quantidade);
            } else {
                if (quantidade > prodAtual.getQuantidade()) {
                    javax.swing.JOptionPane.showMessageDialog(this,
                            "⚠ Estoque insuficiente!\n\n"
                            + "Produto: " + prodAtual.getNome() + "\n"
                            + "Estoque atual: " + prodAtual.getQuantidade() + "\n"
                            + "Quantidade solicitada: " + quantidade + "\n\n"
                            + "Operação cancelada.",
                            "Estoque Insuficiente", javax.swing.JOptionPane.WARNING_MESSAGE);
                    return;
                }
                prodAtual.saidaEstoque(quantidade);
            }

            produtoDAO.atualizar(prodAtual);

            modelo.Movimentacao mov = new modelo.Movimentacao();
            mov.setProduto(prodAtual);
            mov.setData(java.time.LocalDate.now());
            mov.setQuantidade(quantidade);
            mov.setTipo(enums.TipoMovimentacao.valueOf(tipo));
            movimentacaoDAO.inserir(mov);

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Movimentação registrada!\n\nProduto: " + prodAtual.getNome()
                    + "\nTipo: " + tipo
                    + "\nQuantidade: " + quantidade
                    + "\nNovo estoque: " + prodAtual.getQuantidade(),
                    "Sucesso", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        }

        carregarProdutos();
        carregarTabela();
        jSpinner1.setValue(0);
        verificarEstoqueMinimo();
    }

    private void verificarEstoqueMinimo() {
        java.util.List<modelo.Produto> produtos = produtoDAO.listar();
        StringBuilder alertas = new StringBuilder();
        for (modelo.Produto p : produtos) {
            if (p.abaixoMinimo()) {
                alertas.append("ALERTA: ")
                        .append(p.getNome())
                        .append(" está abaixo do estoque mínimo! ")
                        .append("(atual: ").append(p.getQuantidade())
                        .append(", mínimo: ").append(p.getQuantidadeMinima())
                        .append(")  ");
            }
        }
        if (alertas.length() > 0) {
            jLabel6.setText(alertas.toString());
        } else {
            jLabel6.setText("");
        }
    }

    private void preencherCamposComLinhaSelecionada() {
        int linha = jTable1.getSelectedRow();
        if (linha < 0) {
            return;
        }
        jButton3.setVisible(true);
        jButton4.setVisible(true);

        javax.swing.table.DefaultTableModel model
                = (javax.swing.table.DefaultTableModel) jTable1.getModel();

        idMovimentacaoSelecionada = (int) model.getValueAt(linha, 0);
        String nomeProduto = (String) model.getValueAt(linha, 1);
        int qtd = (int) model.getValueAt(linha, 3);
        String tipoStr = (String) model.getValueAt(linha, 4);

        // Seleciona o produto na combobox
        for (int i = 0; i < jComboBox2.getItemCount(); i++) {
            if (jComboBox2.getItemAt(i).startsWith(nomeProduto)) {
                jComboBox2.setSelectedIndex(i);
                break;
            }
        }

        jComboBox1.setSelectedItem(tipoStr);
        jSpinner1.setValue(qtd);

        jButton1.setText("Salvar Edição");
        jButton1.setBackground(new java.awt.Color(255, 140, 0));
    }


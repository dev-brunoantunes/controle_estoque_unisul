    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        int linha = jTable1.getSelectedRow();
        if (linha < 0) {
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Clique em uma linha da tabela para selecionar.",
                    "Atenção", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        javax.swing.table.DefaultTableModel model
                = (javax.swing.table.DefaultTableModel) jTable1.getModel();

        int id = (int) model.getValueAt(linha, 0);

        int confirmacao = javax.swing.JOptionPane.showConfirmDialog(this,
                "Tem certeza que deseja excluir a movimentação ID " + id + "?",
                "Confirmar exclusão",
                javax.swing.JOptionPane.YES_NO_OPTION,
                javax.swing.JOptionPane.WARNING_MESSAGE);

        if (confirmacao == javax.swing.JOptionPane.YES_OPTION) {
            movimentacaoDAO.remover(id);
            idMovimentacaoSelecionada = -1;
            jButton1.setText("Ok");
            jButton1.setBackground(new java.awt.Color(0, 153, 204));
            jTable1.clearSelection();
            jSpinner1.setValue(0);
            carregarTabela();
            verificarEstoqueMinimo();
            javax.swing.JOptionPane.showMessageDialog(this,
                    "Movimentação excluída com sucesso!",
                    "Sucesso", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_jButton4ActionPerformed

